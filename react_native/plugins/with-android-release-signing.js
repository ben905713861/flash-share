const { withAppBuildGradle } = require('@expo/config-plugins');

const MARKER = '// @generated by with-android-release-signing';

module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (configMod) => {
    const contents = configMod.modResults.contents;
    const block = `${MARKER}
def flashShareCredentialsFile = rootProject.file('../credentials.json')
if (!flashShareCredentialsFile.isFile()) {
    throw new GradleException('Missing react_native/credentials.json. Copy credentials.example.json and fill in the Android keystore values.')
}
def flashShareCredentials = new groovy.json.JsonSlurper().parse(flashShareCredentialsFile)
def flashShareAndroidKeystore = flashShareCredentials?.android?.keystore
if (!flashShareAndroidKeystore?.keystorePath || !flashShareAndroidKeystore?.keystorePassword || !flashShareAndroidKeystore?.keyAlias || !flashShareAndroidKeystore?.keyPassword) {
    throw new GradleException('credentials.json must define android.keystore.keystorePath, keystorePassword, keyAlias, and keyPassword.')
}
def flashShareKeystoreFile = new File(flashShareAndroidKeystore.keystorePath.toString())
if (!flashShareKeystoreFile.isAbsolute()) {
    flashShareKeystoreFile = new File(flashShareCredentialsFile.parentFile, flashShareAndroidKeystore.keystorePath.toString())
}

android {
    signingConfigs {
        release {
            storeFile flashShareKeystoreFile
            storePassword flashShareAndroidKeystore.keystorePassword
            keyAlias flashShareAndroidKeystore.keyAlias
            keyPassword flashShareAndroidKeystore.keyPassword
        }
    }
    buildTypes {
        release {
            signingConfig signingConfigs.release
        }
    }
}
`;

    const withoutPreviousBlock = contents.replace(
      new RegExp(`${MARKER}[\\s\\S]*$`),
      ''
    );
    configMod.modResults.contents = `${withoutPreviousBlock.trimEnd()}\n\n${block}`;
    return configMod;
  });
};
